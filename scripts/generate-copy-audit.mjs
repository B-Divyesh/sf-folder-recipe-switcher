import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { renderedCopy } from '../site/src/copy.mjs';

const root = process.cwd();
const auditPath = resolve(root, '.factory/copy-audit.md');
const banned = ['leverage', 'seamless', 'effortless', 'robust', 'powerful', 'intuitive', 'reimagine', 'supercharge', 'unlock', 'delightful', 'journey', 'ecosystem', 'ai-powered'];

function text(value) {
  return value
    .replace(/<[^>]*>/g, ' ')
    .replace(/&(?:amp|lt|gt|quot|#39);/g, (entity) => ({ '&amp;': '&', '&lt;': '<', '&gt;': '>', '&quot;': '"', '&#39;': "'" })[entity])
    .replace(/\s+/g, ' ')
    .trim();
}

function wordCount(value) {
  return value.trim() ? value.trim().split(/\s+/).length : 0;
}

function sentences(value) {
  return value.split(/(?<=[.!?])\s+(?=[A-Z`])/).map((sentence) => sentence.trim()).filter(Boolean);
}

function htmlCopy(source, html) {
  const items = [];
  const add = (value) => { const valueText = text(value); if (valueText) items.push(valueText); };
  for (const match of html.matchAll(/<(h[1-4]|p|a|button|li|figcaption)\b[^>]*>([\s\S]*?)<\/\1>/gi)) add(match[2]);
  for (const match of html.matchAll(/<meta\b[^>]*(?:name|property)="(?:description|og:(?:title|description)|twitter:(?:title|description))"[^>]*content="([^"]+)"[^>]*>/gi)) add(match[1]);
  for (const match of html.matchAll(/<img\b[^>]*\balt="([^"]+)"[^>]*>/gi)) add(match[1]);
  return items.flatMap((value) => sentences(value).map((sentence) => ({ source, value: sentence })));
}

function readmeCopy(markdown) {
  const items = [];
  let inCode = false;
  for (const rawLine of markdown.split('\n')) {
    const line = rawLine.trim();
    if (line.startsWith('```')) { inCode = !inCode; continue; }
    if (inCode || !line || line.startsWith('#') || line.startsWith('>') || line.startsWith('- ')) continue;
    items.push(...sentences(line.replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')).map((value) => ({ source: 'README.md', value })));
  }
  return items;
}

const htmlFiles = [
  ['site/index.html', 'site/index.html'],
  ['site/public/privacy/index.html', 'site/public/privacy/index.html'],
  ['site/public/terms/index.html', 'site/public/terms/index.html'],
  ['site/public/404.html', 'site/public/404.html'],
];
const collected = (await Promise.all(htmlFiles.map(async ([source, file]) => htmlCopy(source, await readFile(resolve(root, file), 'utf8'))))).flat();
collected.push(...readmeCopy(await readFile(resolve(root, 'README.md'), 'utf8')));
collected.push(...renderedCopy.map((value) => ({ source: 'site/src/copy.mjs', value })));

const unique = [];
for (const item of collected) {
  const existing = unique.find((candidate) => candidate.value === item.value);
  if (existing) existing.source += `, ${item.source}`;
  else unique.push({ ...item });
}
const flags = unique.flatMap(({ source, value }) => {
  const reasons = [];
  if (wordCount(value) > 22) reasons.push(`more than 22 words (${wordCount(value)})`);
  const found = banned.filter((word) => new RegExp(`\\b${word.replace('-', '[- ]')}\\b`, 'i').test(value));
  if (found.length) reasons.push(`banned word: ${found.join(', ')}`);
  return reasons.map((reason) => ({ source, value, reason }));
});
const rows = unique.map(({ source, value }) => `| ${wordCount(value)} | ${value.replaceAll('|', '\\|')} | ${source} |`).join('\n');
const flagText = flags.length
  ? flags.map(({ source, value, reason }) => `- ${reason}: “${value}” (${source})`).join('\n')
  : 'No sentence exceeds 22 words and no banned word appears.';
const output = `# Copy audit\n\nGenerated by \`node scripts/generate-copy-audit.mjs\`. Counts use one whitespace-delimited \`wordCount\` function. The audit reads static HTML, README prose, metadata, image alt text, actions, facts, and exported rendered/error strings.\n\n## Terminology\n\n| Concept | Visitor term | Technical field when needed |\n| --- | --- | --- |\n| Saved folder record | recipe file | \`.photo-recipe.json\` |\n| Editor choice | editor profile | \`editor_mappings\` |\n| File formats found | file types | \`extensions\` |\n| Parent-provided record | inherited recipe | source recipe-file path |\n| Safe trial data | demo | isolated page-memory sample |\n\n## Audited copy\n\n| Words | Copy | Source |\n| ---: | --- | --- |\n${rows}\n\n## Flags\n\n${flagText}\n`;

if (process.argv.includes('--check')) {
  const current = await readFile(auditPath, 'utf8');
  if (current !== output) throw new Error('Copy audit is stale. Run node scripts/generate-copy-audit.mjs.');
  if (flags.length) throw new Error(`Copy audit has ${flags.length} unresolved flag(s).`);
} else {
  await writeFile(auditPath, output);
  if (flags.length) throw new Error(`Copy audit has ${flags.length} unresolved flag(s).`);
}
